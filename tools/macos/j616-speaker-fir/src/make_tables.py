# J616 variant, lane SF 2026-10-21. Measures any mono IEEE-float32 WAV with the same code:
# the J616 FIR set written by run_j616.py and asahi-audio's J316 FIRs.
import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import j616_common as C  # noqa: E402

WOOFER_BAND = (50.0, 300.0)      # pink-noise-weighted level bands used for the balance numbers
TWEETER_BAND = (2000.0, 16000.0)
FULL_BAND = (20.0, 20000.0)


def measure(path):
    rate, h = C.read_wav_float32(path)
    row = {'file': str(path), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'rate': rate,
           'taps': len(h), 'peak': float(np.max(np.abs(h))), 'peak_index': int(np.argmax(np.abs(h))),
           'dc_gain': float(np.sum(h)), 'l1': float(np.sum(np.abs(h))),
           'response_db': dict(zip(map(str, C.TABLE_HZ), C.response_db(h, rate)))}
    spec = np.abs(np.fft.rfft(h, 1 << 17))
    k = int(np.argmax(spec))
    row['max_gain_db'] = float(20 * np.log10(spec[k]))
    row['max_gain_hz'] = float(k * rate / (1 << 17))
    for label, band in (('woofer_band', WOOFER_BAND), ('tweeter_band', TWEETER_BAND), ('full_band', FULL_BAND)):
        row[label + '_pink_db'] = C.band_mean_power_db(h, rate, *band)
    return row


def md_table(title, rows):
    head = ['file', 'taps', 'peak'] + [f'{f} Hz' if f < 1000 else f'{f // 1000}k' for f in C.TABLE_HZ] + ['max dB @ Hz', 'sha256']
    out = [f'### {title}', '', '| ' + ' | '.join(head) + ' |', '|' + '|'.join(['---'] * len(head)) + '|']
    for r in rows:
        out.append('| ' + ' | '.join([r['label'], str(r['taps']), f"{r['peak']:.4f}"] +
                                       [f"{r['response_db'][str(f)]:.1f}" for f in C.TABLE_HZ] + [f"`{r['sha256'][:16]}…`"]) + ' |')
    return '\n'.join(out) + '\n'


def balance_table(title, rows):
    out = [f'### {title}', '',
           f'Pink-noise-weighted level (mean |H|² on a log grid): woofer lane over {WOOFER_BAND[0]:.0f}–{WOOFER_BAND[1]:.0f} Hz, '
           f'tweeter lane over {TWEETER_BAND[0]:.0f}–{TWEETER_BAND[1]:.0f} Hz, and each lane over 20 Hz–20 kHz.', '',
           '| set | woofer band (dB) | tweeter band (dB) | woofer − tweeter (dB) | woofer 20–20k (dB) | tweeter 20–20k (dB) |',
           '|---|---:|---:|---:|---:|---:|']
    for label, w, t in rows:
        out.append(f"| {label} | {w['woofer_band_pink_db']:.1f} | {t['tweeter_band_pink_db']:.1f} | "
                   f"{w['woofer_band_pink_db'] - t['tweeter_band_pink_db']:.1f} | {w['full_band_pink_db']:.1f} | {t['full_band_pink_db']:.1f} |")
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fir-dir', type=Path, required=True)
    ap.add_argument('--j316-dir', type=Path, required=True, help='asahi-audio firs/j316')
    ap.add_argument('--out', type=Path, required=True)
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    result = {'j616': {}, 'j316': {}}
    names = ['woofer-L', 'woofer-R', 'tweeter-L', 'tweeter-R']
    variants = [('cg1.00 (primary)', a.fir_dir)] + [(v.name, v) for v in sorted((a.fir_dir / 'variants').iterdir())]
    md = ['# J616 FIR response tables (generated by make_tables.py)', '',
          'Magnitude in dB of the DTFT of each WAV at the listed frequencies (48 kHz). Same code for J616 and J316.', '']
    bal = []
    for vlabel, vdir in variants:
        rows = []
        for n in names:
            m = measure(vdir / f'j616-{n}-48000.wav')
            m['label'] = f'j616-{n}'
            rows.append(m)
            result['j616'].setdefault(vlabel, {})[n] = m
        md.append(md_table(f'J616 {vlabel}', rows))
        bal.append((f'J616 {vlabel}', result['j616'][vlabel]['woofer-L'], result['j616'][vlabel]['tweeter-L']))
    j = []
    for n in ('woofers', 'tweeters'):
        m = measure(a.j316_dir / f'{n}-48.wav')
        m['label'] = f'j316 {n}-48'
        result['j316'][n] = m
        j.append(m)
    md.append(md_table('asahi-audio J316 (firs/j316, 48 kHz files)', j))
    bal.append(('J316 (asahi-audio)', result['j316']['woofers'], result['j316']['tweeters']))
    md.append(balance_table('Woofer / tweeter level balance', bal))
    # J616 minus J316 (dB), the change a swap of the FIRs makes at each frequency
    head = ['lane / set'] + [f'{f} Hz' if f < 1000 else f'{f // 1000}k' for f in C.TABLE_HZ]
    delta = ['### J616 minus J316 (dB at each frequency; negative = the J616 file is quieter)', '',
             '| ' + ' | '.join(head) + ' |', '|' + '|'.join(['---'] * len(head)) + '|']
    for vlabel, _ in variants:
        for lane, key, ref in (('woofer', 'woofer-L', 'woofers'), ('tweeter', 'tweeter-L', 'tweeters')):
            r = result['j616'][vlabel][key]['response_db']
            q = result['j316'][ref]['response_db']
            delta.append(f'| {lane} {vlabel} | ' + ' | '.join(f'{r[str(f)] - q[str(f)]:+.1f}' for f in C.TABLE_HZ) + ' |')
    md.append('\n'.join(delta) + '\n')
    (a.out / 'response-tables.md').write_text('\n'.join(md))
    (a.out / 'response-tables.json').write_text(json.dumps(result, indent=2) + '\n')
    # CSV with the requested columns for each file
    lines = ['set,file,taps,peak,' + ','.join(f'db_{f}' for f in C.TABLE_HZ) + ',max_gain_db,max_gain_hz,sha256']
    for vlabel, d in result['j616'].items():
        for n, m in d.items():
            lines.append(','.join([f'J616 {vlabel}', f'j616-{n}-48000.wav', str(m['taps']), f"{m['peak']:.6f}"] +
                                  [f"{m['response_db'][str(f)]:.2f}" for f in C.TABLE_HZ] + [f"{m['max_gain_db']:.2f}", f"{m['max_gain_hz']:.0f}", m['sha256']]))
    for n, m in result['j316'].items():
        lines.append(','.join(['J316', f'{n}-48.wav', str(m['taps']), f"{m['peak']:.6f}"] +
                              [f"{m['response_db'][str(f)]:.2f}" for f in C.TABLE_HZ] + [f"{m['max_gain_db']:.2f}", f"{m['max_gain_hz']:.0f}", m['sha256']]))
    (a.out / 'response-tables.csv').write_text('\n'.join(lines) + '\n')
    print('\n'.join(md[:1]), 'tables written to', a.out)


if __name__ == '__main__':
    main()
