import json
import sys
from pathlib import Path

ORDER = ['NFP', 'Norm', 'VirtBass', 'Tone1', 'LeftGain', 'RightGain', 'LeftBalance', 'RightBalance', 'XTC', 'Tone2', 'VarEQ', 'Comp',
         'analytical', 'ControlFreakLF', 'ControlFreakHF', 'SpeakerProtect', 'Ramp']
VERDICT = {
    'NFP': ('guard, no audio effect', 'no', 'DSPGraph internal box `nfnp` (not an AudioUnit, cannot be rendered); non-finite-sample guard; 20 B preset with no gain'),
    'Norm': ('DYNAMIC', 'no', 'loudness normalisation: small-signal gain +2.9 dB, falls to -3.8 dB at 0.9 peak'),
    'VirtBass': ('NONLINEAR (harmonic generator), not LTI', 'no', '60 Hz sine: 3rd harmonic -90.9 / -64.7 / -37.5 dB re fundamental at 0.02 / 0.1 / 0.5 amplitude (grows with the cube); its impulse response does not predict its sine response (-3.2 dB vs +2.6 dB at 60 Hz)'),
    'Tone1': ('STATIC, volume independent', 'YES', 'one active filter: 60 Hz high-pass (-3.0 dB at 60 Hz, -25 dB at 40 Hz); all else 0 dB'),
    'LeftGain': ('gain box, graph-driven', 'no (0 dB at 100 % volume, inferred)', 'dbgn param 0 (dB) is overwritten by graph parameter `mvol`; `mmut` mutes; the stored -8.51 dB (`_3`) / -36.0 dB (`_0`) is only the initial value'),
    'RightGain': ('gain box, graph-driven', 'no (0 dB at 100 % volume, inferred)', 'same as LeftGain'),
    'LeftBalance': ('gain box, graph-driven', 'no', 'dbgn, stored 0 dB, driven by `lbal`'),
    'RightBalance': ('gain box, graph-driven', 'no', 'dbgn, stored 0 dB, driven by `rbal`'),
    'XTC': ('linear 2x2 mixer, NOT per channel', 'no (asked to leave out)', 'for centred content (L=R) it is exactly 0 dB at every frequency; it only reshapes the L-R part (+3.0 dB at 1 kHz, -5.2 dB at 5 kHz); its own System Volume parameter changes it but the dspg does not wire it'),
    'Tone2': ('STATIC, volume independent', 'YES', 'six filters, all within +-1.4 dB between 300 Hz and 16 kHz'),
    'VarEQ': ('LINEAR but VOLUME DEPENDENT', 'YES, at a chosen Current Gain', 'Current Gain (graph `mvsc`, 0..1) changes the response a lot: at 1.0 about +7 to +10 dB from 150 Hz up and -19.6 dB at 20 Hz; towards 0 the bass rises to +23 dB at 20 Hz. Level independent (0.5 vs 1e-4 impulse: 9e-8)'),
    'Comp': ('DYNAMIC (multiband compressor)', 'no', 'small-signal +2.0..+2.6 dB (a static make-up that is NOT in the FIRs), compresses only near full scale (spread 1.5 dB at 0.9 peak)'),
    'analytical': ('STATIC, volume independent', 'YES', '6 channels, no cross-channel leakage; woofer lanes (0,1,3,4) and tweeter lanes (2,5) carry different filters via the per-filter channel mask'),
    'ControlFreakLF': ('DYNAMIC (limiter), unity below it', 'no', 'InputGain/OutputGain stored as 0 dB; unity gain at every level tested up to 0.9; with +12 dB InputGain at 0.9 amplitude it limits to peak 1.0'),
    'ControlFreakHF': ('DYNAMIC (limiter), unity below it', 'no', 'same as ControlFreakLF'),
    'SpeakerProtect': ('DYNAMIC (protection)', 'no', 'not measurable offline: needs the telemetry input and calibration properties; stand-alone it sits at its fail-safe -20.0 dB'),
    'Ramp': ('gain box, graph-driven', 'no', 'dbgn stored 0 dB; start/stop ramp via `rpss`'),
}


def main(src, dst):
    q = json.loads(Path(src).read_text())
    out = ['# Q1: AID35 speaker graph inventory (generated by render_q1_md.py from q1-inventory.json)', '',
           'Order = `builtin_speaker_out.dspg` wire order (gain/balance boxes sit between Tone1 and XTC). `_3` = this Mac (speakerID 3) = the generic strip, one inode.', '',
           '| # | stage | AU | preset (`_3`) | generic = `_3` | `_0` | static? | in the FIRs | evidence |', '|---|---|---|---|---|---|---|---|---|']
    for i, name in enumerate(ORDER, 1):
        s = q['stages'][name]
        v = VERDICT[name]
        zero = 'same data' if s['data_equals_0'] else f"different (`{s['preset_name_in_0']}`)" if s['preset_name_in_0'] else 'different data'
        out.append(f"| {i} | {name} | {s['au']} | {s['preset_name'] or '-'} | {'identical' if s['generic_equals_3'] else 'DIFFERENT'} | {zero} | {v[0]} | {v[1]} | {v[2]} |")
    out += ['', '## Level sweeps (uniform noise on all channels, peak −70 … −1 dBFS; gain per octave band, dB)', '']
    for name in ORDER:
        sw = q['stages'][name].get('static', {}).get('level_sweep')
        if not sw:
            continue
        out += [f'**{name}** (max spread across levels: {sw["max_spread_db"]:.3f} dB)', '', '| peak amplitude | 40–80 | 80–160 | 160–320 | 320–640 | 640–1.3k | 1.3–2.6k | 2.6–5.1k | 5.1–10k | 10–20k | total |', '|---|---|---|---|---|---|---|---|---|---|---|']
        for lv, row in sw['gain_db_by_band_then_total'].items():
            out.append(f'| {lv} | ' + ' | '.join(f'{x:.2f}' for x in row) + ' |')
        out.append('')
    out += ['## Volume (graph `mvsc`) dependence', '']
    for name in ('Tone1', 'Tone2', 'analytical'):
        st = q['stages'][name]['static']
        out.append(f"- **{name}**: SystemVolume (param 3) = 1, 0.5, 0, −20, −100 → impulse responses identical (max |diff| {max(st['max_abs_diff_vs_sysvol_1.0'].values()):.1e}, render noise); 0.5 vs 1e-4 impulse amplitude: {st['amplitude_0.5_vs_1e-4_max_rel_diff']:.1e} relative.")
    out += ['', '**VarEQ** magnitude (dB) vs Current Gain:', '', '| Current Gain | ' + ' | '.join(next(iter(q['stages']['VarEQ']['static']['response_db_by_current_gain'].values())).keys()) + ' |',
            '|---|' + '---|' * 14]
    for cg, row in q['stages']['VarEQ']['static']['response_db_by_current_gain'].items():
        out.append(f'| {cg} | ' + ' | '.join(f'{v:.1f}' for v in row.values()) + ' |')
    x = q['stages']['XTC']['static']
    out += ['', '## XTC settled 2×2 response (impulse from frame 30000, after the 100 ms start-up crossfade), dB', '',
            '| path | ' + ' | '.join(next(iter(x['settled_2x2_response_db'].values()))['L->L'].keys()) + ' |', '|---|' + '---|' * 14]
    for k, v in x['settled_2x2_response_db']['preset'].items():
        out.append(f'| {k} | ' + ' | '.join(f'{d:.1f}' for d in v.values()) + ' |')
    out += ['', f"(An impulse at frame 4096 lands inside the start-up crossfade: L→L peak {x['impulse_at_4096_peak_LL']:.3f} instead of {x['impulse_at_30000_peak_LL']:.3f}. The `System Volume` parameter 16 changes the settled response between 0 dB and about −31 dB; the dspg does not wire it.)", '']
    vb = q['stages']['VirtBass']['static']
    out += ['## VirtBass', '', '60 Hz sine, level of each harmonic in dB relative to the input fundamental:', '', '| amplitude | H1 | H2 | H3 | H4 | H5 |', '|---|---|---|---|---|---|']
    for amp, row in vb['harmonics_60Hz_sine'].items():
        out.append(f'| {amp} | ' + ' | '.join(f'{v:.1f}' for v in row.values()) + ' |')
    out += ['', 'Magnitude of the 1e-5 impulse response, dB (NOT a valid linear model: it gives ' + f"{vb['small_signal_impulse_response_db']['60']:.1f} dB at 60 Hz while a 60 Hz sine comes out at {vb['harmonics_60Hz_sine']['0.02']['H1_db_re_fundamental_in']:+.1f} dB, so the stage is not LTI): " +
            ', '.join(f'{f} Hz {v:.1f}' for f, v in vb['small_signal_impulse_response_db'].items()), '',
            '## ControlFreak input-gain boost (100 Hz sine, measured gain in dB)', '']
    for name in ('ControlFreakLF', 'ControlFreakHF'):
        out.append(f'- {name}: ' + '; '.join(f'{k}: {v:.2f}' for k, v in q['stages'][name]['static']['boosted_input_gain_db_measured'].items()))
    out += ['', '## Stored gains of the dbgn boxes', '']
    for name in ('LeftGain', 'RightGain', 'LeftBalance', 'RightBalance', 'Ramp'):
        out.append(f"- {name}: `_3` {q['stages'][name]['stored_params']['_3']}, `_0` {q['stages'][name]['stored_params']['_0']} (param 0 = gain dB, param 1 = mute)")
    out += ['', '## Host parameters touched during these measurements', ''] + [f'- {k}: {v}' for k, v in q['host_parameters_touched'].items()]
    out += ['', f"SpeakerProtect stand-alone gain: {q['stages']['SpeakerProtect']['static']['standalone_gain_db']:.2f} dB ({q['stages']['SpeakerProtect']['static']['note']})", '']
    Path(dst).write_text('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(*sys.argv[1:3])
